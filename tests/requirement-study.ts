import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {freshState,validateState,makeEnvelope,readEnvelope,mergeRestore} from '../src/learning';
import {recallQueue,nextRecallDate} from '../src/RequirementStudy';
const data=JSON.parse(readFileSync('public/course/catalog.json','utf8'));
const now=Date.parse('2026-09-29T01:00:00Z');const s=freshState();
assert.equal(Object.keys(data.requirementReadings).length,712);
assert.equal(Object.values(data.requirementReadings).filter((r:any)=>r.status==='number-located').length,460);
assert.ok(data.requirementReadings.K0290.articlePages.includes(114));
assert.ok(data.requirementReadings.K0622.unlocatedNumbers.includes(179));
assert.equal(recallQueue(data,s,now,20).length,4);
assert.equal(new Set(recallQueue(data,s,now,90)).size,18);
s.courseRecall=[{id:'recall-1',requirement:'K0712',response:'独立回忆',at:new Date(now-86400000).toISOString(),confidence:'again',nextReviewAt:new Date(now-1).toISOString()}];
assert.equal(recallQueue(data,s,now,20)[0],'K0712');
s.courseRecall[0].nextReviewAt=new Date(now+86400000).toISOString();
assert.ok(!recallQueue(data,s,now,20).includes('K0712'));
assert.equal(Date.parse(nextRecallDate(s,'K0712','again',now))-now,86400000);
assert.equal(Date.parse(nextRecallDate(s,'K0712','recalled',now))-now,3*86400000);
s.courseRecallDraft={queue:['K0001','K0002'],response:'未完成的回忆',show:false};
const restored=validateState(await readEnvelope(await makeEnvelope(s),'archive'));
assert.deepEqual(restored.courseRecall,s.courseRecall);assert.deepEqual(restored.courseRecallDraft,s.courseRecallDraft);
assert.equal(mergeRestore(s,restored).courseRecall.length,1);
const old:any=structuredClone(s);delete old.courseRecall;delete old.courseRecallDraft;
assert.deepEqual(validateState(old).courseRecall,[]);assert.equal(validateState(old).courseRecallDraft,null);
console.log('Requirement anchors, review scheduling, old archives and draft backup passed');
